// AuditLog is the read seam of the Enterprise Audit log (ADR 0022), implemented by
// ee/audit. Core knows only this interface: without a license Licensed is false and
// the page answers 402.
type AuditLog interface {
	Licensed() bool
	// Entries returns up to limit entries matching the filter, newest first, preceding
	// the cursor entry id (0 = from the newest), and the next page's cursor (0 = last page).
	Entries(ctx context.Context, s *ent.Scoped, f events.AuditFilter, cursor int64, limit int) ([]*ent.AuditEntry, int64, error)
	// ExportCSV streams the entries matching the filter, newest first, as CSV.
	ExportCSV(ctx context.Context, s *ent.Scoped, f events.AuditFilter, w io.Writer) error
	// RetentionLicensed reports whether the retention window may be set (ADR 0014).
	RetentionLicensed() bool
}

// Deps is everything the /site handlers are built from. The domain modules are
// the shared singletons the composition root registers once, so /site and /api
// cannot diverge on how a module is constructed.
type Deps struct {
	Accounts *accounts.Accounts
	// Attempts counts failed logins and password-reset mails per account (ADR
	// 0025); login and forgot-password share it.
	Attempts       *accounts.Attempts
	OAuth          *oauthserver.Service
	Bus            *events.Bus
	Cipher         *secrets.Cipher
	Outbound       *outbound.Module
	Segments       *segments.Module
	EventLog       *eventlog.Module
	Contacts       *contacts.Module
	Erasure        *erasure.Module
	Tags           *tags.Module
	Automations    *automations.Module
	Broadcasts     *broadcasts.Module
	Welcome        WelcomeEnqueuer
	SysMail        SystemMailEnqueuer
	SendingDomains *sendingdomains.Module
	Integrations   *integrations.Module
	Tokens         *authtoken.Signer
	Tracker        *tracking.Tracker
	AppURL         string
	Audit          AuditLog
	// Sessions issues the session cookie on login (ADR 0020). The composition
	// root (server.New) builds it from the instance secret and SESSION_TTL.
	Sessions *auth.Sessions
	// SecondFactor enrolls and verifies a User's TOTP Second factor (ADR 0020).
	SecondFactor *secondfactor.Module
	// Clock is the time the site session's expiry and a Two-factor requirement's
	// grace are checked against (ADR 0020); nil means time.Now. Tests inject one to
	// move past a session's lifetime or a grace period.
	Clock func() time.Time
}

func NewHandlers(d Deps) *Handlers {
	now := d.Clock
	if now == nil {
		now = time.Now
	}
	return &Handlers{
		accounts: d.Accounts, attempts: d.Attempts, bus: d.Bus, cipher: d.Cipher, outbound: d.Outbound,
		segments: d.Segments, eventlog: d.EventLog, contacts: d.Contacts, erasure: d.Erasure, tags: d.Tags,
		automations: d.Automations, broadcasts: d.Broadcasts, welcome: d.Welcome,
		sysmail: d.SysMail, sendingDomains: d.SendingDomains, integrations: d.Integrations, tokens: d.Tokens, tracker: d.Tracker, appURL: d.AppURL,
		oauth: d.OAuth, audit: d.Audit, sessions: d.Sessions, secondFactor: d.SecondFactor, now: now,
		challenges: d.Tokens.WithClock(d.Clock),
	}
}

var _ siteapi.Handler = (*Handlers)(nil)

// scopedFor is the site's construction point of the scoped client (ADR 0017): it
// resolves the Workspace addressed by the /w/{slug} path segment through the
// authenticated user's Membership (accounts.Scope) and returns its scoped client.
// Handlers pass the result to the domain modules and never build a *ent.Scoped from
// an int64. Returns an ent NotFound error (mapped to 404) when the slug does not
// exist or the user is not a member.
func (h *Handlers) scopedFor(ctx context.Context, slug string) (*ent.Scoped, error) {
	s, _, err := h.scopedWithRoleFor(ctx, slug)
	return s, err
}

// actor is the signed-in User as the actor of an Audit entry (ADR 0022), with the
// display name snapshotted. A name that cannot be loaded is left empty: the entry is
// still worth recording.
func (h *Handlers) actor(ctx context.Context) events.Actor {
	a := auth.GetSiteAuth(ctx)
	if a == nil {
		return events.Actor{}
	}
	actor := events.Actor{Kind: events.ActorUser, ID: strconv.FormatInt(a.UserID, 10)}
	if u, err := h.accounts.User(ctx, a.UserID); err == nil {
		actor.Name = u.Name
	}
	return actor
}

// scopedWithRoleFor is scopedFor plus the caller's role, for owner/admin-gated
// actions.
func (h *Handlers) scopedWithRoleFor(ctx context.Context, slug string) (*ent.Scoped, membership.Role, error) {
	s, m, err := h.membershipFor(ctx, slug)
	if err != nil {
		return nil, "", err
	}
	return s, m.Role, nil
}

// membershipFor is scopedFor plus the caller's Membership (its User and Workspace
// loaded). It is where the Two-factor requirement is enforced (ADR 0020): once a
// User's grace in a requiring Workspace has ended without a Second factor, every
// request to that Workspace fails with secondfactor.ErrRequired (403
// second_factor_required); other Workspaces and the /me endpoints are unaffected.
func (h *Handlers) membershipFor(ctx context.Context, slug string) (*ent.Scoped, *ent.Membership, error) {
	a := auth.GetSiteAuth(ctx)
	if a == nil {
		return nil, nil, &ent.NotFoundError{}
	}
	s, m, err := h.accounts.Scope(ctx, a.UserID, slug)
	if err != nil {
		return nil, nil, err
	}
	if secondfactor.Withheld(m, h.now()) {
		return nil, nil, secondfactor.ErrRequired
	}
	return s, m, nil
}

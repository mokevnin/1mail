-- Modify "contacts" table
ALTER TABLE "public"."contacts" DROP COLUMN "status";
-- Modify "suppressions" table
ALTER TABLE "public"."suppressions" DROP COLUMN "email", ADD COLUMN "channel" character varying NOT NULL DEFAULT 'email', ADD COLUMN "destination" character varying NOT NULL;
-- Create index "suppressions_workspace_id_channel_destination" to table: "suppressions"
CREATE UNIQUE INDEX "suppressions_workspace_id_channel_destination" ON "public"."suppressions" ("workspace_id", "channel", "destination");
-- Create "unsubscribes" table
CREATE TABLE "public"."unsubscribes" (
  "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "channel" character varying NOT NULL DEFAULT 'email',
  "destination" character varying NOT NULL,
  "sending_source" character varying NOT NULL,
  "contact_id" bigint NULL,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL,
  "workspace_id" bigint NOT NULL,
  PRIMARY KEY ("id"),
  CONSTRAINT "unsubscribes_workspaces_unsubscribes" FOREIGN KEY ("workspace_id") REFERENCES "public"."workspaces" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION
);
-- Create index "unsubscribes_ws_channel_dest" to table: "unsubscribes"
CREATE INDEX "unsubscribes_ws_channel_dest" ON "public"."unsubscribes" ("workspace_id", "channel", "destination");
-- Create index "unsubscribes_ws_channel_dest_source" to table: "unsubscribes"
CREATE UNIQUE INDEX "unsubscribes_ws_channel_dest_source" ON "public"."unsubscribes" ("workspace_id", "channel", "destination", "sending_source");
